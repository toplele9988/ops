// A complete owner workday, real clicks, shared mutable API state, never a sender.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { startLocalServer } from './local-server.mjs';
import { installFixtures, conversationKey } from './fixtures.mjs';
const out = process.env.OUT ?? new URL('../../private_out/r11/ops-day/', import.meta.url).pathname;
await mkdir(out, { recursive: true });
const server = await startLocalServer();
const browser = await chromium.launch({ executablePath: process.env.CHROME, args: ['--no-sandbox'] });
const results = [];
const button = (p, name) => p.getByRole('button', { name, exact: true });
const dialog = p => p.locator('dialog[open]');
const closed = p => p.waitForFunction(() => !document.querySelector('dialog[open]'));
const profile = async p => { const b = p.locator('.profile-toggle'); if (await b.isVisible() && await b.getAttribute('aria-expanded') === 'false') await b.click(); };
try {
  for (const viewport of [{ width: 1440, height: 1000 }, { width: 400, height: 860 }]) {
    const context = await browser.newContext({ viewport, timezoneId: 'America/Los_Angeles' });
    const p = await context.newPage(); p.setDefaultTimeout(12000);
    const problems = [];
    const state = await installFixtures(p, problems);
    p.on('pageerror', e => problems.push(e.message));
    p.on('console', m => { if (m.type() === 'error') problems.push(m.text()); });
    p.on('dialog', d => d.accept());
    await p.clock.setFixedTime(new Date('2030-01-01T00:00:00Z'));
    const go = path => p.goto(server.base + '/app' + path);
    await go('/workbench');
    await p.getByTestId('queue-count').waitFor();
    const before = await p.locator('.queue-item').count();
    await p.locator('[data-kind="buyer_reply"]').getByRole('link', { name: '去回复买家' }).click();
    assert.equal(new URL(p.url()).searchParams.get('conversation'), conversationKey);
    await p.locator('.bubble').first().waitFor();
    await profile(p);
    assert.match(await p.getByLabel('对方当地时间', { exact: true }).innerText(), /Europe\/London/);
    await button(p, 'AI 起草回复').click();
    const reply = p.getByRole('textbox', { name: '回复内容（可编辑）', exact: true });
    await p.waitForFunction(() => document.querySelector('.composer textarea')?.value.includes('I will confirm'));
    await reply.fill('Fictional owner reviewed reply. We will check the specifications.');
    await button(p, '确认发送…').click();
    assert.equal(state.inbox.outbox.length, 0);
    await button(dialog(p), '确认发送').click(); await closed(p);
    await p.getByTestId('dry-run-record').waitFor();
    assert.equal(state.inbox.outbox.length, 1);
    assert.equal(state.inbox.outbox[0].dry_run, 1);
    assert.equal(state.inbox.conversations[0].workflow_state, 'waiting', 'dry-run never pretends the buyer was answered');
    await profile(p); await button(p, '转为案子').click();
    await p.getByLabel('案子名称', { exact: true }).fill('虚构工作日询盘');
    await button(dialog(p), '保存').click(); await closed(p);
    await p.getByRole('link', { name: '虚构工作日询盘 · 询盘', exact: true }).click();
    await p.getByRole('heading', { name: '虚构工作日询盘', exact: true }).waitFor();
    const did = Number(new URL(p.url()).pathname.split('/').at(-1));
    await p.getByLabel('产品名', { exact: true }).fill('虚构灯具');
    await p.getByLabel('数量', { exact: true }).fill('4');
    await p.locator('.row').filter({ has: p.getByLabel('产品名', { exact: true }) }).getByRole('button', { name: '添加', exact: true }).click();
    await p.getByText('虚构灯具', { exact: true }).waitFor();
    await button(p, '确认进入「询价核实」').click();
    await button(p, '确认进入「报价」').click();
    await button(p, '确认进入「谈判」').waitFor();
    assert.equal(state.deals.deals.find(d => d.id === did).stage, 'quoting');
    await button(p, '新建报价').click();
    await p.getByRole('heading', { name: '第 1 轮报价', exact: true }).waitFor();
    await button(p, '选择产品和报价').click();
    await dialog(p).getByRole('button').filter({ hasText: '虚构合格灯具' }).click(); await closed(p);
    await p.getByLabel('第 1 行销售单价', { exact: true }).fill('50');
    await button(p, '保存价格').click();
    await p.getByLabel('交付范围（必填，对客户可见）', { exact: true }).fill('虚构已核对交付范围');
    await button(p, '确认本轮 30%/70% 和交付范围').click();
    await p.getByLabel('贸易术语', { exact: true }).selectOption('FOB');
    await p.getByLabel('报价有效期至', { exact: true }).fill('2030-01-20');
    await button(p, '保存条件').click();
    await p.getByRole('heading', { name: '核价检查通过，发出前仍须人工审阅', exact: true }).waitFor();
    await button(p, '保存报价草稿').click();
    await p.getByRole('status').filter({ hasText: '报价单已保存到案子演练草稿箱，未发送' }).first().waitFor();
    assert.equal(state.deals.outbox.filter(d => d.deal_id === did && d.mode === 'dry-run' && d.state === 'draft').length, 1);
    // Explicit owner action closes this reminder; a dry-run alone cannot remove a real reply obligation.
    await go(`/inbox?conversation=${conversationKey}&state=all`);
    await p.locator('.bubble').first().waitFor(); await profile(p);
    await button(p, '标记已处理').click(); await button(p, '恢复跟进').waitFor();
    await go('/workbench');
    await p.getByTestId('queue-count').waitFor();
    assert.equal(await p.locator('.queue-item').count(), before - 1);
    assert.equal(await p.locator('[data-kind="buyer_reply"]').count(), 0);
    await go('/outbox');
    await p.getByRole('heading', { name: '草稿未发送', exact: true }).waitFor();
    await p.getByText('Fictional owner reviewed reply. We will check the specifications.', { exact: true }).waitFor();
    assert.equal(await p.locator('button').filter({ hasText: /^发送$/ }).count(), 0);
    assert.ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2));
    // Deep-link targeting and timezone behavior must be independent of the device timezone.
    await go(`/inbox?conversation=${conversationKey}&c=invalid-legacy-key&state=all`);
    await p.locator('.bubble').first().waitFor(); await profile(p);
    assert.match(await p.getByLabel('对方当地时间', { exact: true }).innerText(), /00:00/);
    assert.match(await p.locator('.bubble-time').first().innerText(), /8:00|08:00/);
    await go(`/inbox?c=${conversationKey}&state=all`);
    await p.locator('.bubble').first().waitFor();
    await p.route('**/api/v1/triage?**', r => r.fulfill({ json: { items: [{ id: 88, conversation_key: conversationKey, action: 'identity', confidence: 0.8, reason: '虚构归属', status: 'pending', conversation: { channel: 'alibaba', counterpart_name: '虚构待归属买家', preview: '虚构问题', last_at: 1893456000 } }] } }));
    await go(`/triage?conversation=${conversationKey}&suggestion=88`);
    await p.locator('#triage-88[data-queue-target="true"]').waitFor();
    assert.equal(await p.evaluate(() => document.activeElement?.id), 'triage-88');
    await p.route('**/api/v1/pipeline/health', r => r.fulfill({ json: { generated_at: 1893456000, summary: '虚构管道', sources: [], channels: [], notes: [], scorecard: [{ channel: 'alibaba', label: '虚构阿里', result: 'unknown', result_label: '待核对', metrics: [] }], failed_jobs: { status: 'ready', count: 0, items: [] } } }));
    await go('/system/pipeline?channel=alibaba');
    await p.locator('[data-pipeline-channel="alibaba"][data-queue-target="true"]').waitFor();
    assert.equal(await p.evaluate(() => document.activeElement?.getAttribute('data-pipeline-channel')), 'alibaba');
    // An explicit IANA timezone accounts for DST; no fixed UTC offset is used.
    state.parties.parties[0].country = 'GB';
    state.parties.parties[0].timezone = 'Europe/London';
    await p.clock.setFixedTime(new Date('2030-07-01T00:00:00Z'));
    await go('/customers/1');
    assert.match(await p.getByLabel('对方当地时间', { exact: true }).innerText(), /01:00/);
    state.parties.parties[0].country = 'US';
    state.parties.parties[0].timezone = '';
    await p.reload();
    await p.getByRole('article').first().waitFor();
    assert.equal(await p.getByLabel('对方当地时间', { exact: true }).count(), 0, 'multi-zone country needs a confirmed timezone');
    await p.getByRole('link', { name: '新建案子（填写产品）', exact: true }).click();
    await dialog(p).getByLabel('客户', { exact: true }).waitFor();
    assert.equal(await dialog(p).count(), 1);
    assert.equal(await dialog(p).getByLabel('客户', { exact: true }).inputValue(), '1');
    assert.equal(await dialog(p).getByLabel('目的国', { exact: true }).inputValue(), 'US');
    await button(dialog(p), '取消').click();
    await go(`/inbox?conversation=${conversationKey}&state=all`);
    await p.locator('.bubble').first().waitFor(); await profile(p);
    await p.getByRole('link', { name: '填写产品后建案', exact: true }).click();
    await dialog(p).getByLabel('客户会话', { exact: true }).waitFor();
    assert.equal(await dialog(p).count(), 1);
    await p.waitForFunction(key => document.querySelector('dialog[open] select[aria-label="客户会话"]')?.value === key, conversationKey);
    assert.equal(await dialog(p).getByLabel('客户会话', { exact: true }).inputValue(), conversationKey);
    assert.ok(await dialog(p).getByLabel('客户名称', { exact: true }).inputValue());
    await button(dialog(p), '取消').click();
    await p.screenshot({ path: `${out}/${viewport.width}-day.png`, fullPage: true });
    assert.deepEqual(problems, []);
    results.push({ viewport, before, after: before - 1, dryRunReplies: state.inbox.outbox.length, quoteDrafts: state.deals.outbox.length, dealId: did, passed: true });
    console.log(`PASS ops-day ${viewport.width}: queue ${before} -> ${before - 1}, reply and quote remain dry-run`);
    await context.close();
  }
} finally {
  await writeFile(`${out}/results.json`, JSON.stringify(results, null, 2));
  await browser.close(); await server.close();
}
